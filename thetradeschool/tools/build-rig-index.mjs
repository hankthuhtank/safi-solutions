/* Builds js/3d/rig-index.js: which 3D model and which part every topic lives on.
   The page renderer is a classic script and needs this synchronously (to mark topics that have a
   place on the model) without loading three.js. Re-run after editing any model:
     node thetradeschool/tools/build-rig-index.mjs
   Models build without a browser, so this also catches geometry errors. */
import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
const here = dirname(fileURLToPath(import.meta.url));
const kit = await import(join(here, '../js/3d/kit.js'));
const WORLDS = ['electrical', 'hvac', 'plumbing', 'industrial', 'welding', 'construction'];
const out = { models: {}, parts: {}, comps: {} };
for (const w of WORLDS) {
  const mod = await import(join(here, `../js/3d/models/${w}.js`));
  const m = mod.meta, b = mod.build(kit);
  out.models[w] = { name: m.name, plate: m.plate, systems: Object.fromEntries(Object.entries(m.systems).map(([k, s]) => [k, { name: s.name, color: '#' + s.color.toString(16).padStart(6, '0') }])), modes: m.modes || null, layers: m.layers || null };
  out.comps[w] = {};
  for (const c of b.comps) {
    if (!c.concepts?.length) continue;
    out.comps[w][c.id] = c.concepts;
    for (const k of c.concepts) if (!out.parts[k]) out.parts[k] = [w, c.label || '', c.sys];
  }
}
const js = `/* Generated by tools/build-rig-index.mjs. Do not edit by hand. */\nwindow.TRADE_RIG=${JSON.stringify(out)};\n`;
writeFileSync(join(here, '../js/3d/rig-index.js'), js);
console.log(`rig-index: ${Object.keys(out.parts).length} topics on ${WORLDS.length} models`);

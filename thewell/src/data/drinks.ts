import type { Drink, SpecLine, Unit } from "./types";
import { MORE_DRINKS } from "./drinks-more";

type Spec = [string, number, Unit] | [string, number, Unit, true];

function line(s: Spec): SpecLine {
  return { i: s[0], a: s[1], u: s[2], optional: s[3] ? true : undefined };
}

function d(
  partial: Omit<Drink, "spec" | "difficulty" | "ice" | "related" | "era"> & {
    spec: Spec[];
    difficulty?: 1 | 2 | 3;
    ice?: Drink["ice"];
    related?: string[];
    era?: string;
  },
): Drink {
  return {
    difficulty: 2,
    ice: "none",
    related: [],
    era: "classic",
    ...partial,
    spec: partial.spec.map(line),
  };
}

